/** ホームの「使い方」：はじめて使う人向けの短い説明 */
export function Help() {
  return (
    <details className="about">
      <summary>使い方</summary>
      <ol className="compact">
        <li>
          <strong>開く</strong>：MusicXML（MuseScore などで書き出したもの）か MIDI
          を選ぶ。読み込み結果を確かめて「楽譜を開く」。開いた楽譜は端末に自動で保存され、ホームの一覧から続きを開ける
        </li>
        <li>
          <strong>見る・聴く</strong>
          ：上の「総譜」の欄で表示するパートを選ぶ。「記譜／実音」で移調楽器の書き方を切り替える。下の ▶
          で再生（小節をタップするとそこから）
        </li>
        <li>
          <strong>移調</strong>
          ：「移調」で曲の調を変えたり、別の楽器用のパートを作ったりする（例：ヴァイオリンの旋律から
          B♭クラリネットのパート）
        </li>
        <li>
          <strong>直す</strong>
          ：音符をタップすると下に編集ボタンが出る（高さ・長さ・休符・タイなど）。五線の空いた所をタップすると小節を選んでコピー・貼り付けなど。「鍵盤」で音を入れられる。↶
          で元に戻す
        </li>
        <li>
          <strong>編曲</strong>
          ：「編曲」→「編曲案を作る」で木管5重奏の下書きを作る。「楽譜」で元の楽譜と切り替え。割当表で楽器の受け持ちを変え、「編曲の警告」で吹きにくい所を確かめて直す
        </li>
        <li>
          <strong>印刷・共有</strong>：「書き出し」でパート譜・総譜の PDF、MusicXML、プロジェクトのファイルを作る
        </li>
      </ol>
      <p className="muted">
        iPhone・iPad は Safari の「共有 →
        ホーム画面に追加」で使うと、データが消えにくくなります。うまくいかない所があれば、どの曲のどの操作かを教えてください。
      </p>
    </details>
  );
}
